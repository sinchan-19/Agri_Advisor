// AGRI ADVISOR - IMAGE UPLOAD + DISEASE DETECTION
// =========================================================

document.addEventListener("DOMContentLoaded", function () {

    // -----------------------------------------------------
    // HTML ELEMENTS
    // -----------------------------------------------------

    const uploadArea =
        document.getElementById("uploadArea");

    const uploadContent =
        document.getElementById("uploadContent");

    const selectedImageContent =
        document.getElementById("selectedImageContent");

    const imageInput =
        document.getElementById("imageInput");

    const imagePreview =
        document.getElementById("imagePreview");

    const removeImageButton =
        document.getElementById("removeImageButton");

    const removeImageButton2 =
        document.getElementById("removeImageButton2");

    const changeImageButton =
        document.getElementById("changeImageButton");

    const detectButton =
        document.getElementById("detectButton");

    const detectButtonText =
        document.getElementById("detectButtonText");

    const loadingSection =
        document.getElementById("loadingSection");

    const result =
        document.getElementById("result");


    // -----------------------------------------------------
    // INITIAL STATE
    // -----------------------------------------------------

    if (selectedImageContent) {
        selectedImageContent.style.display = "none";
    }

    if (loadingSection) {
        loadingSection.style.display = "none";
    }

    if (result) {
        result.style.display = "none";
    }

    if (detectButton) {
        detectButton.disabled = true;
        detectButton.style.opacity = "0.65";
        detectButton.style.cursor = "not-allowed";
    }


    // -----------------------------------------------------
    // SHOW IMAGE
    // -----------------------------------------------------

    function showSelectedImage(file) {

        if (!file) {
            return;
        }

        const allowedTypes = [
            "image/jpeg",
            "image/png",
            "image/webp"
        ];

        if (!allowedTypes.includes(file.type)) {

            alert(
                "Please select a JPG, JPEG, PNG or WEBP image."
            );

            imageInput.value = "";

            return;
        }


        // Maximum 5 MB

        const maxSize =
            5 * 1024 * 1024;

        if (file.size > maxSize) {

            alert(
                "Image size must be less than 5MB."
            );

            imageInput.value = "";

            return;
        }


        // Create preview

        const imageURL =
            URL.createObjectURL(file);

        if (imagePreview) {

            imagePreview.src =
                imageURL;

        }


        // Hide normal upload area

        if (uploadContent) {

            uploadContent.style.display =
                "none";

        }


        // Show selected image

        if (selectedImageContent) {

            selectedImageContent.style.display =
                "block";

        }


        // Enable detection

        if (detectButton) {

            detectButton.disabled =
                false;

            detectButton.style.opacity =
                "1";

            detectButton.style.cursor =
                "pointer";

        }


        console.log(
            "Image selected:",
            file.name
        );

    }


    // -----------------------------------------------------
    // FILE SELECTION
    // -----------------------------------------------------

    if (imageInput) {

        imageInput.addEventListener(
            "change",
            function () {

                const file =
                    imageInput.files[0];

                if (file) {

                    showSelectedImage(file);

                }

            }
        );

    }


    // -----------------------------------------------------
    // UPLOAD AREA CLICK
    // -----------------------------------------------------

    if (uploadArea) {

        uploadArea.addEventListener(
            "click",
            function (event) {

                // Don't reopen file picker when
                // clicking selected-image buttons

                if (
                    event.target.closest(
                        ".selected-image-content"
                    )
                ) {
                    return;
                }

                if (imageInput) {

                    imageInput.click();

                }

            }
        );

    }


    // -----------------------------------------------------
    // CHANGE IMAGE
    // -----------------------------------------------------

    if (changeImageButton) {

        changeImageButton.addEventListener(
            "click",
            function (event) {

                event.preventDefault();

                event.stopPropagation();

                if (imageInput) {

                    imageInput.click();

                }

            }
        );

    }


    // -----------------------------------------------------
    // REMOVE IMAGE
    // -----------------------------------------------------

    function removeSelectedImage(event) {

        if (event) {

            event.preventDefault();

            event.stopPropagation();

        }


        if (imageInput) {

            imageInput.value = "";

        }


        if (imagePreview) {

            imagePreview.removeAttribute(
                "src"
            );

        }


        if (selectedImageContent) {

            selectedImageContent.style.display =
                "none";

        }


        if (uploadContent) {

            uploadContent.style.display =
                "block";

        }


        if (detectButton) {

            detectButton.disabled =
                true;

            detectButton.style.opacity =
                "0.65";

            detectButton.style.cursor =
                "not-allowed";

        }


        if (result) {

            result.innerHTML = "";

            result.style.display =
                "none";

        }

    }


    if (removeImageButton) {

        removeImageButton.addEventListener(
            "click",
            removeSelectedImage
        );

    }


    if (removeImageButton2) {

        removeImageButton2.addEventListener(
            "click",
            removeSelectedImage
        );

    }


    // -----------------------------------------------------
    // DRAG AND DROP
    // -----------------------------------------------------

    if (uploadArea) {

        uploadArea.addEventListener(
            "dragover",
            function (event) {

                event.preventDefault();

                uploadArea.classList.add(
                    "drag-over"
                );

            }
        );


        uploadArea.addEventListener(
            "dragleave",
            function () {

                uploadArea.classList.remove(
                    "drag-over"
                );

            }
        );


        uploadArea.addEventListener(
            "drop",
            function (event) {

                event.preventDefault();

                uploadArea.classList.remove(
                    "drag-over"
                );


                if (!imageInput) {

                    return;

                }


                const files =
                    event.dataTransfer.files;


                if (
                    !files ||
                    files.length === 0
                ) {

                    return;

                }


                try {

                    const dataTransfer =
                        new DataTransfer();

                    dataTransfer.items.add(
                        files[0]
                    );

                    imageInput.files =
                        dataTransfer.files;


                    imageInput.dispatchEvent(
                        new Event(
                            "change",
                            {
                                bubbles: true
                            }
                        )
                    );

                }

                catch (error) {

                    console.error(
                        "Drag and drop error:",
                        error
                    );

                }

            }
        );

    }


    // -----------------------------------------------------
    // DETECT DISEASE
    // -----------------------------------------------------

    if (detectButton) {

        detectButton.addEventListener(
            "click",
            async function () {

                if (!imageInput) {

                    alert(
                        "Image upload control was not found."
                    );

                    return;

                }


                const file =
                    imageInput.files[0];


                if (!file) {

                    alert(
                        "Please choose a maize image first."
                    );

                    return;

                }


                // Disable button

                detectButton.disabled =
                    true;


                if (detectButtonText) {

                    detectButtonText.textContent =
                        "Analyzing...";

                }


                // Show loading

                if (loadingSection) {

                    loadingSection.style.display =
                        "block";

                }


                if (result) {

                    result.style.display =
                        "none";

                }


                // Create request

                const formData =
                    new FormData();


                formData.append(
                    "file",
                    file
                );


                try {

                    console.log(
                        "Sending image to /predict..."
                    );


                    const response =
                        await fetch(
                            "/predict",
                            {
                                method: "POST",
                                body: formData
                            }
                        );


                    console.log(
                        "Server status:",
                        response.status
                    );


                    const data =
                        await response.json();


                    console.log(
                        "Server response:",
                        data
                    );


                    // -----------------------------------------
                    // NON-MAIZE
                    // -----------------------------------------

                    if (
                        data.is_maize === false
                    ) {

                        const message =
                            data.error ||
                            data.message ||
                            "This image is not recognized as a maize image.";


                        if (result) {

                            result.innerHTML = `

                                <div class="rejected-result">

                                    <h2>
                                        ❌ NON-MAIZE IMAGE
                                    </h2>

                                    <p>
                                        ${message}
                                    </p>

                                    <p>
                                        <strong>
                                            Disease detection was not performed.
                                        </strong>
                                    </p>

                                    <p>
                                        Please upload a clear maize
                                        leaf or maize crop image.
                                    </p>

                                </div>

                            `;

                            result.style.display =
                                "block";

                        }


                        return;

                    }


                    // -----------------------------------------
                    // REJECTED
                    // -----------------------------------------

                    if (
                        data.rejected === true
                    ) {

                        const message =
                            data.error ||
                            data.message ||
                            "The image was rejected.";


                        if (result) {

                            result.innerHTML = `

                                <div class="rejected-result">

                                    <h2>
                                        ❌ IMAGE REJECTED
                                    </h2>

                                    <p>
                                        ${message}
                                    </p>

                                </div>

                            `;

                            result.style.display =
                                "block";

                        }


                        return;

                    }


                    // -----------------------------------------
                    // SERVER ERROR
                    // -----------------------------------------

                    if (!response.ok) {

                        const message =
                            data.error ||
                            data.message ||
                            "Server error occurred.";


                        if (result) {

                            result.innerHTML = `

                                <div class="rejected-result">

                                    <h2>
                                        ⚠️ SERVER ERROR
                                    </h2>

                                    <p>
                                        ${message}
                                    </p>

                                </div>

                            `;

                            result.style.display =
                                "block";

                        }


                        return;

                    }


                    // -----------------------------------------
                    // MAIZE RESULT
                    // -----------------------------------------

                    if (
                        data.is_maize === true
                    ) {

                        const disease =
                            data.disease ||
                            data.prediction ||
                            "Unknown";


                        const diseaseConfidence =
                            Number(
                                data.confidence ||
                                data.disease_confidence ||
                                0
                            );


                        const maizeConfidence =
                            Number(
                                data.maize_confidence ||
                                data.gate_confidence ||
                                0
                            );


                        if (result) {

                            result.innerHTML = `

                                <div class="success-result">

                                    <h2>
                                        🌽 MAIZE IMAGE DETECTED
                                    </h2>

                                    <p>
                                        <strong>
                                            Disease:
                                        </strong>

                                        ${disease}
                                    </p>

                                    <p>
                                        <strong>
                                            Disease Confidence:
                                        </strong>

                                        ${diseaseConfidence.toFixed(2)}%
                                    </p>

                                    <p>
                                        <strong>
                                            Maize Gate Confidence:
                                        </strong>

                                        ${maizeConfidence.toFixed(2)}%
                                    </p>

                                </div>

                            `;

                            result.style.display =
                                "block";

                        }


                        return;

                    }


                    // -----------------------------------------
                    // UNKNOWN RESULT
                    // -----------------------------------------

                    if (result) {

                        result.innerHTML = `

                            <div class="rejected-result">

                                <h2>
                                    ⚠️ IMAGE NOT ACCEPTED
                                </h2>

                                <p>
                                    The AI could not safely
                                    identify this image.
                                </p>

                                <p>
                                    Please upload a clear maize
                                    leaf or maize crop image.
                                </p>

                            </div>

                        `;

                        result.style.display =
                            "block";

                    }

                }


                catch (error) {

                    console.error(
                        "Prediction error:",
                        error
                    );


                    if (result) {

                        result.innerHTML = `

                            <div class="rejected-result">

                                <h2>
                                    ❌ CONNECTION ERROR
                                </h2>

                                <p>
                                    Could not connect to the
                                    Agri Advisor server.
                                </p>

                                <p>
                                    Please make sure Flask is running.
                                </p>

                            </div>

                        `;

                        result.style.display =
                            "block";

                    }

                }


                finally {

                    if (loadingSection) {

                        loadingSection.style.display =
                            "none";

                    }


                    if (detectButton) {

                        detectButton.disabled =
                            false;

                    }


                    if (detectButtonText) {

                        detectButtonText.textContent =
                            "Detect Maize Disease";

                    }

                }

            }
        );

    }


    console.log(
        "Agri Advisor image detection system loaded."
    );

});