// LANGUAGE SELECTOR
// =========================================================

document.addEventListener(
    "DOMContentLoaded",
    function() {

        const languageSelector =
            document.getElementById(
                "languageSelector"
            );


        const savedLanguage =
            localStorage.getItem(
                "agriAdvisorLanguage"
            ) || "en";


        if (languageSelector) {

            languageSelector.value =
                savedLanguage;


            languageSelector.addEventListener(
                "change",
                function() {

                    changeLanguage(
                        this.value
                    );

                }
            );

        }


        changeLanguage(
            savedLanguage
        );

    }
);
